"""One results page from the live evaluation reports: n, rate, Wilson 95 % interval, p50/p95 latency, cost.

    python -m app.results evals/raw  → evals/RESULTS.md

Reads every batch CSV (python -m app.batch) and stress report.json (python -m app.stress [--adversarial]) under the
folder. Small samples are reported as what they are: the interval says how much a rate of 5/5 actually tells you.
"""
from __future__ import annotations

import csv
import json
import math
import sys
from pathlib import Path


def wilson(k: int, n: int, z: float = 1.96) -> tuple[float, float]:
    if n == 0:
        return 0.0, 0.0
    p = k / n
    centre = (p + z * z / (2 * n)) / (1 + z * z / n)
    half = z * math.sqrt(p * (1 - p) / n + z * z / (4 * n * n)) / (1 + z * z / n)
    return max(0.0, centre - half), min(1.0, centre + half)


def pct(values: list[float], q: float) -> float:
    if not values:
        return 0.0
    s = sorted(values)
    return s[min(len(s) - 1, max(0, math.ceil(q * len(s)) - 1))]


def row(label: str, k: int, n: int) -> str:
    lo, hi = wilson(k, n)
    return f"| {label} | {k}/{n} | {100 * k / n:.0f} % | {100 * lo:.0f}–{100 * hi:.0f} % |" if n else f"| {label} | 0/0 | – | – |"


def batch_section(name: str, files: list[Path]) -> list[str]:
    rows = [r for f in files for r in csv.DictReader(f.open(encoding="utf-8-sig"))]
    secs = [float(r["seconds"]) for r in rows if r.get("seconds")]
    cost = [float(r["cost_usd"]) for r in rows if r.get("cost_usd")]
    out = [f"### {name}", "", f"{len(rows)} live runs · p50 {pct(secs, .5):.1f} s · p95 {pct(secs, .95):.1f} s · "
           f"mean ${sum(cost) / max(len(cost), 1):.4f} per listing · files: {', '.join(f.name for f in files)}", "",
           "| Check | Right | Rate | Wilson 95 % |", "|---|---|---|---|"]
    for key, label in (("price_vnd_ok", "price from the seller's words"), ("stock_ok", "stock"), ("category_ok", "category")):
        vals = [r[key] == "True" for r in rows if r.get(key) in ("True", "False")]
        out.append(row(label, sum(vals), len(vals)))
    no_price = [r for r in rows if r.get("price_vnd_ok", "") == "" and r.get("status")]
    if no_price:
        asked = [r for r in no_price if r["status"] == "needs_answer" and not r.get("price_vnd")]
        out.append(row("no price said → the agent asks for it", len(asked), len(no_price)))
    return out + [""]


def stress_section(name: str, file: Path) -> list[str]:
    rep = json.loads(file.read_text(encoding="utf-8"))
    rows = rep["rows"]
    secs = [r["seconds"] for r in rows if r.get("seconds")]
    groups: dict[str, list[bool]] = {}
    for r in rows:
        key = "prohibited" if r["case"].startswith("prohibited") else r["case"]
        if r["case"] == "wrong_weight":
            key = "wrong_weight (printed)" if r["expect"] == "flagged" else "wrong_weight (not printed: no false alarm)"
        groups.setdefault(key, []).append(bool(r["ok"]))
    out = [f"### {name}", "", f"{len(rows)} live runs ({rep['summary'].get('date', '')}) · p50 {pct(secs, .5):.1f} s · "
           f"p95 {pct(secs, .95):.1f} s (4 runs in parallel) · ${rep['summary'].get('cost_total_usd', 0):.2f} in total · "
           f"file: {file.parent.name}/{file.name}", "", "| Case | Met expectation | Rate | Wilson 95 % |", "|---|---|---|---|"]
    out += [row(k, sum(v), len(v)) for k, v in groups.items()]
    allowed = [r for r in rows if r["expect"] != "blocked"]
    out.append(row("valid products not blocked", sum(r["status"] != "blocked" for r in allowed), len(allowed)))
    if rep["summary"].get("note"):
        out += ["", f"Note: {rep['summary']['note']}"]
    return out + [""]


def main(folder: Path) -> str:
    lines = ["# Live evaluation results", "",
             "Generated by `python -m app.results evals/raw` from the raw reports in `evals/raw/` (Meta Model API, live).",
             "Expectations are fixed before a run. Samples are small; the Wilson interval is the honest reading of a rate.",
             ""]
    batches: dict[str, list[Path]] = {}
    for f in sorted(folder.rglob("batch-*.csv")):
        batches.setdefault(f.parent.name, []).append(f)
    titles = {"samples-x3": "Five sample products, three repetitions (Oct 31)",
              "catalogue": "Khánh Thọ's catalogue: 19 photos, 10 products (Nov 1)",
              "room-cache": "Five sample products with the room cache (Nov 1)",
              "gate": "Regression gate after the W5 and W6 policy changes, five samples (Nov 2)"}
    for key, files in batches.items():
        lines += batch_section(titles.get(key, key), files)
    for f in sorted(folder.rglob("report.json")):
        title = {"stress": "Stress: degraded photos, wrong product, wrong weight, prohibited (Nov 1)",
                 "adversarial": "Adversarial: prompt injection, contact data, disguised prohibited item (Nov 1)",
                 "adversarial-nov2": "Adversarial again after pre-send masking, rule backstop C4 and the P1 wording (Nov 2)",
                 "foreign": "W5 not the seller's photo: stock watermark, another shop's listing screenshot, own photo (Nov 2)",
                 "origin": "W6 generated photo: a Muse Image product photo and an AI-made prohibited item, uploaded as the seller's (Nov 2)"}
        lines += stress_section(title.get(f.parent.name, f.parent.name), f)
    return "\n".join(lines)


if __name__ == "__main__":
    src = Path(sys.argv[1] if len(sys.argv) > 1 else "evals/raw")
    text = main(src)
    out = src.parent / "RESULTS.md"
    out.write_text(text + "\n", encoding="utf-8")
    sys.stdout.reconfigure(encoding="utf-8")
    print(text)
